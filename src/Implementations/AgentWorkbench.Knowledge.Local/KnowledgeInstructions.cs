namespace AgentWorkbench.Knowledge.Local;

/// <summary>
/// 知识问答的系统指令（run 级，经 harness 的 <c>AIContextProvider</c> 注入，不写进会话历史）。
/// </summary>
/// <remarks>
/// <para>
/// 检索已工具化：不再由服务端预检索、把【资料】段拼进系统提示词，而是由模型主动调用
/// MCP 工具 <c>mcp__rag__search_knowledge</c>（Python server 执行）——每次检索因此在
/// 轨迹里留名、可回放、可判分。服务端只负责拿到结果后做引用校验，判定不搬进工具侧。
/// </para>
/// <para>
/// 引用格式是 <c>[n]</c>，n 取自工具结果里的 <c>no</c> 字段。换成编号而不是「文件名 + 片段序号」，
/// 是因为后者要靠文本匹配回指——模型缩写一次文件名（《H5U手册》对《汇川H5U系列…手册》），
/// 引用就会被判成越界，把真出处误杀。编号是封闭空间里的一次选择，服务端按同一顺序还原，不存在这种模糊。
/// </para>
/// </remarks>
public static class KnowledgeInstructions
{
    /// <summary>
    /// 唯一入口的指令：先判断这句话属于哪一类，再决定查资料、查系统、提动作还是直答。
    /// </summary>
    /// <remarks>
    /// 原先是两条入口各带一句提示词，由用户在界面上选「通用对话 / 知识库问答」。
    /// 那个开关不改变工具集，只改变措辞——它给的是一个不存在的选择权，已删。
    /// 现在由模型自己判意图，所以这里必须把四类情况写全，并且**不能要求闲聊也去检索**：
    /// 一句「帮我写封邮件」若被强制先查企业资料，只会得到一次毫无意义的检索和一句拒答。
    /// <para>
    /// 最后一句针对的是实测抓到过的事故：模型在零工具调用的情况下声称「已创建」，界面上
    /// 看起来一切正常。指令不能替代代码校验，但至少不能给它许可。
    /// </para>
    /// </remarks>
    public const string Entry =
        "你的回答可能涉及企业资料、企业系统里的具体数据，或者与这两者无关的一般问题。回答前先判断属于哪一类：\n"
        + "1. 涉及企业规章、制度、流程、手册、产品资料：先调用 mcp__rag__search_knowledge 检索，只依据检索结果作答，"
        + "每个结论后用方括号标注出处，编号取自检索结果每条的 no 字段（例如 [2]；多条写作 [1,3]）。"
        + "检索为空或不足以回答时，直接说“资料不足以回答该问题”，不要用资料以外的知识补足；"
        + "资料相关但确实没提到问的那一项时，明确写“资料中未提及这一项”。\n"
        + "2. 涉及企业内部的具体数据（某张单据、某个状态、某个数量）：调用对应的查询动作去取，不要凭印象作答。"
        + "查不到就如实说查不到，不要把“没查到”说成“没有”。\n"
        + "3. 需要改动企业系统：只能通过动作工具提出，由系统走审批后执行。不得声称自己已经执行、已经创建或已经发送，"
        + "执行结果以工具返回为准。\n"
        + "4. 与上述无关的一般问题：可以直接回答，但不得把常识包装成企业事实。\n"
        + "任何情况下都不得编造工具调用、工具结果或已经完成的动作。";

    /// <summary>「依据资料回答」的强检索指令：先检索、只依据资料、标注出处、不足则如实说。</summary>
    /// <remarks>
    /// 唯一入口不再使用它：那个入口要允许闲聊直答，强制检索会把闲聊变成拒答。
    /// 保留给纯资料问答场景（批量问答、检索评测），那里没有「这句话是不是闲聊」的判断问题。
    /// </remarks>
    public const string AnswerWithCitations =
        "你是严谨的资料问答助手。回答前必须先调用 mcp__rag__search_knowledge 工具检索资料。\n"
        + "只能依据检索到的资料作答，不得使用资料之外的知识，也不得编造。\n"
        + "每个结论后用方括号编号标注出处，编号取自检索结果每条的 no 字段（例如 [2]；多条写作 [1,3]）。\n"
        + "只能引用最近一次检索结果里出现过的编号，不要自己编编号。\n"
        + "若检索结果为空或不足以回答，直接回答“资料不足以回答该问题”，不要凭猜测作答。\n"
        + "若资料与问题有关、但里面没有问的那个具体信息（例如问保修期，手册只讲接线），"
        + "要明确写出“资料中未提及这一项”。不要用手册以外的常识补足——补出来的句子没有出处，"
        + "读者会把它当作有据可查的内容。";
}
